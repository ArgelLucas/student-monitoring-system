-- StudentMonitor Phase 2: academic terms, class offerings and historical enrollments.
-- Apply ONLY after reviewed migrations 001–006 and a restorable database backup.
-- This schema adds EMPTY tables. It never imports, moves or deletes student data.
-- Legacy attendance and gradebook behavior remain unchanged in Phase 2.
BEGIN;

CREATE TABLE IF NOT EXISTS public.academic_years (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label text NOT NULL UNIQUE CHECK (label ~ '^20[0-9]{2}-20[0-9]{2}$'),
  starts_on date NOT NULL,
  ends_on date NOT NULL,
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT academic_year_dates_valid CHECK (ends_on > starts_on)
);

CREATE TABLE IF NOT EXISTS public.academic_terms (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_year_id bigint NOT NULL REFERENCES public.academic_years(id),
  name text NOT NULL CHECK (name IN ('1st Semester','2nd Semester')),
  starts_on date NOT NULL,
  ends_on date NOT NULL,
  status text NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned','active','archived')),
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (academic_year_id,name),
  CONSTRAINT academic_term_dates_valid CHECK (ends_on >= starts_on)
);

-- An offering identifies ONE subject taught to ONE section in ONE term.
-- Sections, subjects and student identities are not duplicated.
CREATE TABLE IF NOT EXISTS public.class_offerings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_term_id bigint NOT NULL REFERENCES public.academic_terms(id),
  section_id bigint NOT NULL REFERENCES public.sections(id),
  subject_id bigint NOT NULL REFERENCES public.subjects(id),
  instructor_user_id uuid NOT NULL REFERENCES public.admin_users(user_id),
  program text CHECK (program IS NULL OR length(btrim(program)) BETWEEN 2 AND 80),
  year_level smallint CHECK (year_level IS NULL OR year_level BETWEEN 1 AND 6),
  room text CHECK (room IS NULL OR length(btrim(room)) BETWEEN 1 AND 80),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (academic_term_id,section_id,subject_id)
);
CREATE INDEX IF NOT EXISTS class_offerings_term_idx
  ON public.class_offerings(academic_term_id,section_id,subject_id);

-- A point-in-time COPY of the existing published timetable. Changing an
-- operational class_schedules row will not silently rewrite past term schedules.
CREATE TABLE IF NOT EXISTS public.class_offering_meetings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id bigint NOT NULL REFERENCES public.class_offerings(id),
  source_schedule_id bigint REFERENCES public.class_schedules(id) ON DELETE SET NULL,
  weekday smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),
  start_time time NOT NULL,
  end_time time NOT NULL,
  UNIQUE (offering_id,weekday,start_time),
  CHECK (end_time > start_time)
);
CREATE INDEX IF NOT EXISTS class_offering_meetings_offering_idx
  ON public.class_offering_meetings(offering_id);

-- One canonical student number can be enrolled in several offerings.
-- Name/section snapshots survive later edits to the official roster.
-- Enrollment rows are NEVER physically deleted by the web application.
CREATE TABLE IF NOT EXISTS public.class_enrollments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id bigint NOT NULL REFERENCES public.class_offerings(id),
  student_number text NOT NULL REFERENCES public.student_roster(student_number),
  surname_at_enrollment text NOT NULL,
  first_name_at_enrollment text NOT NULL,
  middle_initial_at_enrollment text NOT NULL,
  section_id_at_enrollment bigint NOT NULL REFERENCES public.sections(id),
  enrolled_on date NOT NULL,
  status text NOT NULL DEFAULT 'enrolled'
    CHECK (status IN ('enrolled','dropped','completed')),
  status_reason text,
  status_changed_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (offering_id,student_number),
  CHECK (status_reason IS NULL OR length(status_reason) <= 500)
);
CREATE INDEX IF NOT EXISTS class_enrollments_offering_idx
  ON public.class_enrollments(offering_id,status,student_number);
CREATE INDEX IF NOT EXISTS class_enrollments_student_idx
  ON public.class_enrollments(student_number,offering_id);

-- Explicit admin-only SELECT permissions. No direct browser writes to any new
-- academic table; all mutations go through vetted SECURITY DEFINER RPCs.
ALTER TABLE public.academic_years ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.academic_terms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.class_offerings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.class_offering_meetings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.class_enrollments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.academic_years,public.academic_terms,
  public.class_offerings,public.class_offering_meetings,
  public.class_enrollments FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.academic_years,public.academic_terms,
  public.class_offerings,public.class_offering_meetings,
  public.class_enrollments TO authenticated;

DROP POLICY IF EXISTS academic_years_admin_read ON public.academic_years;
CREATE POLICY academic_years_admin_read ON public.academic_years
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));
DROP POLICY IF EXISTS academic_terms_admin_read ON public.academic_terms;
CREATE POLICY academic_terms_admin_read ON public.academic_terms
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));
DROP POLICY IF EXISTS class_offerings_admin_read ON public.class_offerings;
CREATE POLICY class_offerings_admin_read ON public.class_offerings
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));
DROP POLICY IF EXISTS class_offering_meetings_admin_read ON public.class_offering_meetings;
CREATE POLICY class_offering_meetings_admin_read ON public.class_offering_meetings
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));
DROP POLICY IF EXISTS class_enrollments_admin_read ON public.class_enrollments;
CREATE POLICY class_enrollments_admin_read ON public.class_enrollments
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));

CREATE OR REPLACE FUNCTION public.admin_create_academic_year(
  p_label text,p_starts_on date,p_ends_on date
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_id bigint; v_label text := btrim(coalesce(p_label,''));
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator session required' USING ERRCODE='42501';
  END IF;
  IF v_label !~ '^20[0-9]{2}-20[0-9]{2}$'
     OR substring(v_label,6,4)::int <> substring(v_label,1,4)::int+1
     OR p_starts_on IS NULL OR p_ends_on IS NULL OR p_ends_on<=p_starts_on THEN
    RAISE EXCEPTION 'Enter a valid academic year and date range';
  END IF;
  INSERT INTO public.academic_years(label,starts_on,ends_on,created_by)
  VALUES(v_label,p_starts_on,p_ends_on,auth.uid()) RETURNING id INTO v_id;
  INSERT INTO public.audit_logs(actor_id,action,details)
  VALUES(auth.uid(),'academic.year.created',
    pg_catalog.jsonb_build_object('academic_year_id',v_id,'label',v_label));
  RETURN v_id;
END; $$;

CREATE OR REPLACE FUNCTION public.admin_create_academic_term(
  p_academic_year_id bigint,p_name text,p_starts_on date,p_ends_on date
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_year public.academic_years%ROWTYPE; v_id bigint;
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator session required' USING ERRCODE='42501';
  END IF;
  SELECT * INTO v_year FROM public.academic_years WHERE id=p_academic_year_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Academic year not found'; END IF;
  IF p_name NOT IN ('1st Semester','2nd Semester') OR p_name IS NULL
     OR p_starts_on IS NULL OR p_ends_on IS NULL
     OR p_starts_on < v_year.starts_on OR p_ends_on > v_year.ends_on
     OR p_ends_on < p_starts_on THEN
    RAISE EXCEPTION 'Term must be within the selected academic year';
  END IF;
  IF EXISTS (SELECT 1 FROM public.academic_terms t
    WHERE t.academic_year_id=v_year.id
      AND t.starts_on<=p_ends_on AND t.ends_on>=p_starts_on) THEN
    RAISE EXCEPTION 'Term dates overlap an existing semester';
  END IF;
  INSERT INTO public.academic_terms(
    academic_year_id,name,starts_on,ends_on,created_by
  ) VALUES (v_year.id,p_name,p_starts_on,p_ends_on,auth.uid())
  RETURNING id INTO v_id;
  INSERT INTO public.audit_logs(actor_id,action,details)
  VALUES(auth.uid(),'academic.term.created',
    pg_catalog.jsonb_build_object('academic_term_id',v_id,'academic_year_id',v_year.id,'name',p_name));
  RETURN v_id;
END; $$;

CREATE OR REPLACE FUNCTION public.admin_create_class_offering(
  p_academic_term_id bigint,p_section_id bigint,p_subject_id bigint,
  p_program text DEFAULT NULL,p_year_level smallint DEFAULT NULL,p_room text DEFAULT NULL
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_term public.academic_terms%ROWTYPE; v_id bigint;
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator session required' USING ERRCODE='42501';
  END IF;
  SELECT * INTO v_term FROM public.academic_terms
    WHERE id=p_academic_term_id FOR SHARE;
  IF NOT FOUND OR v_term.status='archived' THEN
    RAISE EXCEPTION 'Choose a semester that is not archived';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.sections s WHERE s.id=p_section_id AND s.is_active)
     OR NOT EXISTS (SELECT 1 FROM public.subjects s WHERE s.id=p_subject_id AND s.is_active)
     OR NOT EXISTS (SELECT 1 FROM public.class_schedules cs
       WHERE cs.section_id=p_section_id AND cs.subject_id=p_subject_id) THEN
    RAISE EXCEPTION 'Section and subject must match a published class schedule';
  END IF;
  INSERT INTO public.class_offerings(
    academic_term_id,section_id,subject_id,instructor_user_id,
    program,year_level,room,created_by
  ) VALUES (
    v_term.id,p_section_id,p_subject_id,auth.uid(),
    NULLIF(btrim(coalesce(p_program,'')),''),
    p_year_level,NULLIF(btrim(coalesce(p_room,'')),''),
    auth.uid()
  ) RETURNING id INTO v_id;
  INSERT INTO public.class_offering_meetings(
    offering_id,source_schedule_id,weekday,start_time,end_time
  ) SELECT v_id,s.id,s.weekday,s.start_time,s.end_time
    FROM public.class_schedules s
    WHERE s.section_id=p_section_id AND s.subject_id=p_subject_id;
  INSERT INTO public.audit_logs(actor_id,action,details)
  VALUES(auth.uid(),'academic.class.created',
    pg_catalog.jsonb_build_object('offering_id',v_id,'term_id',v_term.id,
       'section_id',p_section_id,'subject_id',p_subject_id));
  RETURN v_id;
END; $$;

-- Instructor explicitly selects student numbers; no automatic identity
-- matching or bulk import based on names. All validations are atomic.
CREATE OR REPLACE FUNCTION public.admin_enroll_class_students(
  p_offering_id bigint,p_student_numbers text[],p_enrolled_on date
) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_offering public.class_offerings%ROWTYPE;
  v_term public.academic_terms%ROWTYPE;
  v_roster public.student_roster%ROWTYPE;
  v_number text;
  v_total integer := 0;
  v_added integer := 0;
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator session required' USING ERRCODE='42501';
  END IF;
  IF p_student_numbers IS NULL OR cardinality(p_student_numbers)=0
     OR cardinality(p_student_numbers)>200 THEN
    RAISE EXCEPTION 'Select 1–200 students per enrollment operation';
  END IF;
  SELECT * INTO v_offering FROM public.class_offerings
    WHERE id=p_offering_id FOR UPDATE;
  IF NOT FOUND OR v_offering.status<>'active' THEN
    RAISE EXCEPTION 'Class is missing or archived';
  END IF;
  SELECT * INTO v_term FROM public.academic_terms
    WHERE id=v_offering.academic_term_id;
  IF NOT FOUND OR v_term.status='archived' THEN
    RAISE EXCEPTION 'Semester is archived';
  END IF;
  IF p_enrolled_on IS NULL OR p_enrolled_on<v_term.starts_on OR p_enrolled_on>v_term.ends_on THEN
    RAISE EXCEPTION 'Enrollment date must fall within the selected semester';
  END IF;
  FOR v_number IN SELECT DISTINCT btrim(x)
    FROM pg_catalog.unnest(p_student_numbers) AS x ORDER BY 1
  LOOP
    IF v_number IS NULL OR v_number !~ '^[0-9]{8,15}$' THEN
      RAISE EXCEPTION 'Invalid student number in the selected enrollment list';
    END IF;
    SELECT * INTO v_roster FROM public.student_roster
      WHERE student_number=v_number AND active FOR SHARE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'A selected student is missing from the active official roster';
    END IF;
    IF v_roster.section_id<>v_offering.section_id THEN
      RAISE EXCEPTION 'Student section does not match this class offering';
    END IF;
    INSERT INTO public.class_enrollments(
      offering_id,student_number,surname_at_enrollment,first_name_at_enrollment,
      middle_initial_at_enrollment,section_id_at_enrollment,enrolled_on,created_by
    ) VALUES (
      v_offering.id,v_roster.student_number,v_roster.surname,v_roster.first_name,
      v_roster.middle_initial,v_roster.section_id,p_enrolled_on,auth.uid()
    ) ON CONFLICT (offering_id,student_number) DO NOTHING;
    GET DIAGNOSTICS v_added=ROW_COUNT;
    v_total:=v_total+v_added;
  END LOOP;
  IF v_total>0 THEN
    INSERT INTO public.audit_logs(actor_id,action,details)
    VALUES(auth.uid(),'academic.students.enrolled',
      pg_catalog.jsonb_build_object('offering_id',v_offering.id,
        'added_count',v_total,'enrolled_on',p_enrolled_on));
  END IF;
  RETURN v_total;
END; $$;

-- Preserve the enrollment row when students drop or complete a class.
CREATE OR REPLACE FUNCTION public.admin_update_enrollment_status(
  p_enrollment_id bigint,p_status text,p_reason text
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_item public.class_enrollments%ROWTYPE;
  v_offering public.class_offerings%ROWTYPE;
  v_reason text := btrim(coalesce(p_reason,''));
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator session required' USING ERRCODE='42501';
  END IF;
  IF p_status IS NULL OR p_status NOT IN ('enrolled','dropped','completed')
    OR length(v_reason)<8 OR length(v_reason)>500 THEN
    RAISE EXCEPTION 'Choose a valid status and enter a reason (8–500 characters)';
  END IF;
  SELECT * INTO v_item FROM public.class_enrollments WHERE id=p_enrollment_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Enrollment not found'; END IF;
  SELECT * INTO v_offering FROM public.class_offerings
    WHERE id=v_item.offering_id;
  IF v_offering.status='archived' THEN
    RAISE EXCEPTION 'Archived class enrollment cannot be changed';
  END IF;
  IF v_item.status=p_status THEN
    RAISE EXCEPTION 'Enrollment already has that status';
  END IF;
  UPDATE public.class_enrollments SET status=p_status,
    status_reason=v_reason,status_changed_at=now()
    WHERE id=v_item.id;
  INSERT INTO public.audit_logs(actor_id,action,details)
  VALUES(auth.uid(),'academic.enrollment.status_changed',
    pg_catalog.jsonb_build_object('enrollment_id',v_item.id,
      'offering_id',v_item.offering_id,'old_status',v_item.status,
      'new_status',p_status,'reason',v_reason));
END; $$;

-- Archiving is irreversible from this UI; enrollment and schedule snapshots remain.
CREATE OR REPLACE FUNCTION public.admin_archive_class_offering(
  p_offering_id bigint
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_item public.class_offerings%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator session required' USING ERRCODE='42501';
  END IF;
  SELECT * INTO v_item FROM public.class_offerings WHERE id=p_offering_id FOR UPDATE;
  IF NOT FOUND OR v_item.status='archived' THEN RAISE EXCEPTION 'Class already archived or missing'; END IF;
  UPDATE public.class_offerings SET status='archived',updated_at=now() WHERE id=p_offering_id;
  INSERT INTO public.audit_logs(actor_id,action,details)
  VALUES(auth.uid(),'academic.class.archived',
    pg_catalog.jsonb_build_object('offering_id',v_item.id,'term_id',v_item.academic_term_id));
END; $$;

