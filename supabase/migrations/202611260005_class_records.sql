-- StudentMonitor v6.2 · instructor-only gradebook (source: uploaded grading sheet)
-- PREREQUISITE: migrations 001–004, including private roster import.
-- This migration creates EMPTY grade tables. It NEVER imports historical grades.
BEGIN;

CREATE TABLE IF NOT EXISTS public.class_record_assessments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id bigint NOT NULL REFERENCES public.sections(id),
  subject_id bigint NOT NULL REFERENCES public.subjects(id),
  academic_year text NOT NULL CHECK (academic_year ~ '^20[0-9]{2}-20[0-9]{2}$'),
  semester text NOT NULL CHECK (semester IN ('1st Semester','2nd Semester')),
  term text NOT NULL CHECK (term IN ('Midterm','Final')),
  category text NOT NULL CHECK (category IN ('Activities','Quizzes','Attendance','Projects','Examinations')),
  title text NOT NULL CHECK (char_length(trim(title)) BETWEEN 1 AND 80),
  max_score numeric(8,2) NOT NULL CHECK (max_score > 0 AND max_score <= 1000),
  assessment_date date NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')::date,
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS class_record_assessments_section_idx
  ON public.class_record_assessments(academic_year,semester,section_id,subject_id,term,assessment_date,id);

CREATE TABLE IF NOT EXISTS public.class_record_scores (
  assessment_id bigint NOT NULL REFERENCES public.class_record_assessments(id) ON DELETE CASCADE,
  student_number text NOT NULL REFERENCES public.student_roster(student_number),
  score numeric(8,2) NOT NULL CHECK (score >= 0),
  updated_by uuid REFERENCES auth.users(id),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (assessment_id,student_number)
);
CREATE INDEX IF NOT EXISTS class_record_scores_student_idx
  ON public.class_record_scores(student_number);

-- Read/write privileges alone are insufficient; all policies require admin
-- status. Students and anonymous visitors cannot query gradebook tables.
ALTER TABLE public.class_record_assessments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.class_record_scores ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.class_record_assessments, public.class_record_scores FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.class_record_assessments TO authenticated;
GRANT SELECT ON public.class_record_scores TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.class_record_assessments_id_seq TO authenticated;

DROP POLICY IF EXISTS class_record_assessments_admin ON public.class_record_assessments;
CREATE POLICY class_record_assessments_admin ON public.class_record_assessments
  FOR ALL TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
DROP POLICY IF EXISTS class_record_scores_admin ON public.class_record_scores;
CREATE POLICY class_record_scores_admin ON public.class_record_scores
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));

-- Never allow scores for a different section or higher than the assessment's
-- maximum. Enforce on the server (not only in JavaScript).
CREATE OR REPLACE FUNCTION public.validate_class_record_score()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_section bigint; v_max numeric;
BEGIN
  SELECT a.section_id,a.max_score INTO v_section,v_max
    FROM public.class_record_assessments a WHERE a.id=NEW.assessment_id;
  IF v_section IS NULL THEN RAISE EXCEPTION 'Assessment not found'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.student_roster r
    WHERE r.student_number=NEW.student_number AND r.active AND r.section_id=v_section) THEN
    RAISE EXCEPTION 'Student is not active in the selected class section';
  END IF;
  IF NEW.score > v_max THEN RAISE EXCEPTION 'Score exceeds the assessment maximum'; END IF;
  NEW.updated_by=auth.uid(); NEW.updated_at=now();
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS class_record_score_validation ON public.class_record_scores;
CREATE TRIGGER class_record_score_validation
BEFORE INSERT OR UPDATE ON public.class_record_scores
FOR EACH ROW EXECUTE FUNCTION public.validate_class_record_score();
REVOKE ALL ON FUNCTION public.validate_class_record_score() FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.validate_class_record_assessment()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.class_schedules s
    WHERE s.section_id=NEW.section_id AND s.subject_id=NEW.subject_id) THEN
    RAISE EXCEPTION 'Subject is not assigned to this section';
  END IF;
  IF TG_OP='UPDATE' AND (NEW.section_id IS DISTINCT FROM OLD.section_id
    OR NEW.subject_id IS DISTINCT FROM OLD.subject_id) THEN
    RAISE EXCEPTION 'Cannot move an assessment between classes';
  END IF;
  NEW.updated_at=now();
  IF TG_OP='INSERT' THEN NEW.created_by=auth.uid(); END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS class_record_assessment_validation ON public.class_record_assessments;
CREATE TRIGGER class_record_assessment_validation
BEFORE INSERT OR UPDATE ON public.class_record_assessments
FOR EACH ROW EXECUTE FUNCTION public.validate_class_record_assessment();
REVOKE ALL ON FUNCTION public.validate_class_record_assessment() FROM PUBLIC,anon,authenticated;
-- Every grade change is stored with the actor and prior/new score.
CREATE TABLE IF NOT EXISTS public.class_record_changes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id bigint REFERENCES public.class_record_assessments(id) ON DELETE SET NULL,
  assessment_title text NOT NULL,
  academic_year text NOT NULL,
  semester text NOT NULL,
  section_id bigint NOT NULL,
  subject_id bigint NOT NULL,
  term text NOT NULL,
  student_number text NOT NULL REFERENCES public.student_roster(student_number),
  old_score numeric(8,2),
  new_score numeric(8,2),
  changed_by uuid NOT NULL REFERENCES auth.users(id),
  changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS class_record_changes_lookup_idx
  ON public.class_record_changes(assessment_id,student_number,changed_at DESC);
ALTER TABLE public.class_record_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.class_record_changes FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.class_record_changes TO authenticated;
DROP POLICY IF EXISTS class_record_changes_admin_read ON public.class_record_changes;
CREATE POLICY class_record_changes_admin_read ON public.class_record_changes
  FOR SELECT TO authenticated USING ((SELECT public.is_admin()));

-- Transactional grade saving: client cannot write scores directly.
-- A malformed entry, invalid score or unauthorized caller rolls back the batch.
CREATE OR REPLACE FUNCTION public.save_class_record_scores(p_changes jsonb)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_item jsonb;
  v_id bigint;
  v_student text;
  v_score numeric(8,2);
  v_old numeric(8,2);
  v_assessment public.class_record_assessments%ROWTYPE;
  v_existing boolean;
  v_count integer := 0;
BEGIN
  IF auth.uid() IS NULL OR NOT public.portal_session_active() OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only signed-in instructors can save class scores' USING ERRCODE='28000';
  END IF;
  IF pg_catalog.jsonb_typeof(p_changes) IS DISTINCT FROM 'array' OR
    pg_catalog.jsonb_array_length(p_changes)>5000 THEN
    RAISE EXCEPTION 'Provide at most 5000 score changes per save';
  END IF;
  FOR v_item IN SELECT value FROM pg_catalog.jsonb_array_elements(p_changes) LOOP
    IF pg_catalog.jsonb_typeof(v_item) <> 'object' OR
       coalesce(v_item->>'assessment_id','') !~ '^[0-9]{1,18}$' OR
       coalesce(v_item->>'student_number','') !~ '^[0-9]{8,15}$' OR
       (v_item->'score' IS NOT NULL AND pg_catalog.jsonb_typeof(v_item->'score') NOT IN ('null','number')) THEN
      RAISE EXCEPTION 'Invalid score entry';
    END IF;
    v_id := (v_item->>'assessment_id')::bigint;
    SELECT * INTO v_assessment FROM public.class_record_assessments WHERE id=v_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Assessment no longer exists'; END IF;
    v_student := v_item->>'student_number';
    v_score := CASE WHEN v_item->>'score' IS NULL THEN NULL ELSE (v_item->>'score')::numeric END;
    SELECT score INTO v_old FROM public.class_record_scores
      WHERE assessment_id=v_id AND student_number=v_student FOR UPDATE;
    v_existing:=FOUND;
    IF v_score IS NULL THEN
      DELETE FROM public.class_record_scores WHERE assessment_id=v_id AND student_number=v_student;
    ELSE
      INSERT INTO public.class_record_scores(assessment_id,student_number,score)
        VALUES(v_id,v_student,v_score)
      ON CONFLICT(assessment_id,student_number) DO UPDATE SET score=excluded.score;
    END IF;
    IF (v_existing AND v_old IS DISTINCT FROM v_score) OR (NOT v_existing AND v_score IS NOT NULL) THEN
      INSERT INTO public.class_record_changes(
        assessment_id,assessment_title,academic_year,semester,section_id,subject_id,term,
        student_number,old_score,new_score,changed_by)
      VALUES(v_id,v_assessment.title,v_assessment.academic_year,v_assessment.semester,v_assessment.section_id,v_assessment.subject_id,
        v_assessment.term,v_student,v_old,v_score,auth.uid());
      v_count:=v_count+1;
    END IF;
  END LOOP;
  RETURN v_count;
END;
$$;
REVOKE ALL ON FUNCTION public.save_class_record_scores(jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.save_class_record_scores(jsonb) TO authenticated;
COMMIT;
