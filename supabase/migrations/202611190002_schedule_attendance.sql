-- Student Monitoring System: section-specific class schedules and admin-gated check-ins.
-- Apply AFTER 202611190001_initial.sql. This migration also works if you already
-- ran the separate class_schedules SQL from the class schedule setup guide.
-- All class-day checks use Asia/Manila time on the DATABASE, never device time.

begin;

-- 1. Sections/subjects supplied by the instructor. Safe to run repeatedly.
insert into public.sections (code) values
  ('1A'), ('1B'), ('2A'), ('2B'), ('3A'), ('3B')
on conflict (code) do update set is_active = true;

insert into public.subjects (code, name) values
  ('CT 123a', 'CT 123a'), ('CT 223a', 'CT 223a'),
  ('QCA 113', 'QCA 113'), ('CT 304', 'CT 304')
on conflict (code) do update set name = excluded.name, is_active = true;

-- 2. 14 weekly class meetings. ISO weekdays: Monday=1 ... Sunday=7.
create table if not exists public.class_schedules (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id),
  subject_id bigint not null references public.subjects(id),
  weekday smallint not null check (weekday between 1 and 7),
  start_time time not null,
  end_time time not null,
  constraint class_schedules_time_order check (end_time > start_time),
  unique (section_id, subject_id, weekday, start_time)
);

insert into public.class_schedules (section_id, subject_id, weekday, start_time, end_time)
select sec.id, sub.id, schedule.weekday, schedule.start_time::time, schedule.end_time::time
from (values
  ('1A','CT 123a',2,'09:00','12:00'),
  ('1A','CT 123a',5,'15:00','17:00'),
  ('1B','CT 123a',2,'13:00','16:00'),
  ('1B','CT 123a',5,'13:00','15:00'),
  ('2A','CT 223a',3,'13:00','15:00'),
  ('2A','QCA 113',4,'09:00','12:00'),
  ('2A','CT 223a',4,'16:00','19:00'),
  ('2B','QCA 113',2,'16:00','19:00'),
  ('2B','CT 223a',3,'16:00','19:00'),
  ('2B','CT 223a',4,'13:00','15:00'),
  ('3A','CT 304',1,'13:00','16:00'),
  ('3A','CT 304',5,'08:00','10:00'),
  ('3B','CT 304',1,'16:00','19:00'),
  ('3B','CT 304',5,'10:00','12:00')
) as schedule(section_code, subject_code, weekday, start_time, end_time)
join public.sections sec on sec.code = schedule.section_code
join public.subjects sub on sub.code = schedule.subject_code
on conflict (section_id, subject_id, weekday, start_time)
do update set end_time = excluded.end_time;

-- 3. Each meeting has an explicit admin-controlled check-in window.
-- One window per scheduled class on each Philippine calendar date.
create table if not exists public.attendance_windows (
  id bigint generated by default as identity primary key,
  schedule_id bigint not null references public.class_schedules(id),
  meeting_date date not null,
  is_open boolean not null default true,
  opened_at timestamptz not null default now(),
  expires_at timestamptz not null,
  closed_at timestamptz,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  constraint attendance_windows_valid_times check (expires_at > opened_at),
  constraint attendance_windows_unique_meeting unique (schedule_id, meeting_date)
);

-- Historical attendance from v0.1.0 is preserved with a NULL window ID.
-- New submissions must be attached to a specific class window by the RPC.
alter table public.attendance_records
  add column if not exists attendance_window_id bigint references public.attendance_windows(id);
alter table public.attendance_records
  drop constraint if exists attendance_records_student_id_subject_id_attendance_date_key;
create unique index if not exists attendance_one_per_window_idx
  on public.attendance_records(student_id, attendance_window_id)
  where attendance_window_id is not null;
create index if not exists attendance_window_session_idx
  on public.attendance_records(attendance_window_id);

-- 4. Browser clients can SELECT permitted schedules/windows but cannot modify them.
alter table public.class_schedules enable row level security;
alter table public.attendance_windows enable row level security;
revoke all on public.class_schedules, public.attendance_windows from public, anon, authenticated;
grant select on public.class_schedules, public.attendance_windows to authenticated;

drop policy if exists class_schedules_read on public.class_schedules;
create policy class_schedules_read on public.class_schedules
for select to authenticated using (
  (select public.is_admin())
  or (
    (select public.is_approved_student())
    and exists (
      select 1 from public.student_profiles p
      where p.user_id = (select auth.uid()) and p.section_id = class_schedules.section_id
    )
  )
);

drop policy if exists attendance_windows_read on public.attendance_windows;
create policy attendance_windows_read on public.attendance_windows
for select to authenticated using (
  (select public.is_admin())
  or (
    (select public.is_approved_student())
    and exists (
      select 1 from public.student_profiles p
      join public.class_schedules s on s.id = attendance_windows.schedule_id
      where p.user_id = (select auth.uid()) and p.section_id = s.section_id
    )
  )
);

-- The profile form needs eligible subject choices before student approval.
-- Only the section/subject association is returned, not private records.
create or replace function public.list_section_subjects()
returns table(section_id bigint, subject_id bigint)
language sql stable security definer set search_path = '' as $$
  select distinct s.section_id, s.subject_id
  from public.class_schedules s
  join public.sections sec on sec.id = s.section_id and sec.is_active
  join public.subjects sub on sub.id = s.subject_id and sub.is_active
  where public.portal_session_active();
$$;

revoke all on function public.list_section_subjects() from public, anon, authenticated;
grant execute on function public.list_section_subjects() to authenticated;

-- 5. Refuse a profile whose selected subject does not belong to its section.
-- Students in sections 2A/2B may attend BOTH of their scheduled subjects,
-- regardless of which of the two they chose as their profile's primary subject.
create or replace function public.save_student_profile(
  p_surname text, p_first_name text, p_middle_initial text,
  p_sex text, p_age integer, p_section_id bigint,
  p_subject_id bigint, p_github_username text
) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_github text := public.current_github_username();
  v_handle text := lower(trim(coalesce(p_github_username, '')));
  v_profile public.student_profiles%rowtype;
begin
  if not public.portal_session_active() or v_uid is null then
    raise exception 'Session expired; sign in again' using errcode = '28000';
  end if;
  if v_github is null or v_handle <> v_github then
    raise exception 'GitHub username must match your authenticated GitHub account';
  end if;
  if v_handle !~ '^[a-z0-9](?:[a-z0-9-]{0,37}[a-z0-9])?$' then
    raise exception 'Invalid GitHub username';
  end if;
  if trim(coalesce(p_surname, '')) = '' or char_length(trim(p_surname)) > 80
     or trim(coalesce(p_first_name, '')) = '' or char_length(trim(p_first_name)) > 80
     or (coalesce(trim(p_middle_initial),'') !~ '^[A-Za-z]$'
         and coalesce(trim(p_middle_initial),'') <> 'N/A')
     or p_sex is null or p_sex not in ('Male','Female','Prefer not to say')
     or p_age is null or p_age not between 12 and 99 then
    raise exception 'Student information is incomplete or invalid';
  end if;
  if not exists (select 1 from public.sections where id = p_section_id and is_active)
     or not exists (select 1 from public.subjects where id = p_subject_id and is_active)
     or not exists (
       select 1 from public.class_schedules s
       where s.section_id = p_section_id and s.subject_id = p_subject_id
     ) then
    raise exception 'Select a valid subject scheduled for your section';
  end if;

  select * into v_profile from public.student_profiles where user_id = v_uid for update;
  if found and v_profile.is_approved and
     (v_profile.section_id is distinct from p_section_id or
      v_profile.subject_id is distinct from p_subject_id) then
    raise exception 'Ask the administrator before changing an approved section or subject';
  end if;

  insert into public.student_profiles(
    user_id, surname, first_name, middle_initial, sex, age,
    section_id, subject_id, github_username
  ) values (
    v_uid, trim(p_surname), trim(p_first_name), trim(p_middle_initial), p_sex,
    p_age, p_section_id, p_subject_id, v_handle
  )
  on conflict (user_id) do update set
    surname = excluded.surname, first_name = excluded.first_name,
    middle_initial = excluded.middle_initial, sex = excluded.sex,
    age = excluded.age, section_id = excluded.section_id,
    subject_id = excluded.subject_id, github_username = excluded.github_username,
    updated_at = now();

  insert into public.audit_logs(actor_id, action, subject_user_id)
  values (v_uid, 'profile.saved', v_uid);
end;
$$;

-- 6. Admin opens the window ONLY during the scheduled class period in Manila.
-- Reopening within the same day preserves the window ID and avoids duplicates.
create or replace function public.open_class_attendance(p_schedule_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_schedule public.class_schedules%rowtype;
  v_manila timestamp := now() at time zone 'Asia/Manila';
  v_now timestamptz := now();
  v_end timestamptz;
  v_window public.attendance_windows%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  select s.* into v_schedule
  from public.class_schedules s
  join public.sections sec on sec.id = s.section_id and sec.is_active
  join public.subjects sub on sub.id = s.subject_id and sub.is_active
  where s.id = p_schedule_id;
  if not found then raise exception 'Class schedule not found'; end if;

  if extract(isodow from v_manila)::smallint <> v_schedule.weekday
     or v_manila::time < v_schedule.start_time
     or v_manila::time >= v_schedule.end_time then
    raise exception 'You may open attendance only during this class time (Asia/Manila)';
  end if;

  v_end := (v_manila::date + v_schedule.end_time) at time zone 'Asia/Manila';
  insert into public.attendance_windows (
    schedule_id, meeting_date, opened_at, expires_at, created_by,
    is_open, closed_at
  ) values (
    v_schedule.id, v_manila::date, v_now, v_end, auth.uid(), true, null
  ) on conflict (schedule_id, meeting_date) do update
    set is_open = true, closed_at = null, opened_at = excluded.opened_at,
        expires_at = excluded.expires_at, created_by = excluded.created_by
  returning * into v_window;

  insert into public.audit_logs(actor_id, action)
  values (auth.uid(), 'attendance.window.opened');
  return jsonb_build_object('window_id', v_window.id,
    'meeting_date', v_window.meeting_date, 'expires_at', v_window.expires_at);
end;
$$;

-- 7. Admin can close attendance immediately.
create or replace function public.close_class_attendance(p_schedule_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_today date := (now() at time zone 'Asia/Manila')::date;
begin
  if not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  update public.attendance_windows set is_open = false, closed_at = now()
  where schedule_id = p_schedule_id and meeting_date = v_today and is_open = true;
  if not found then raise exception 'No open attendance window for this class today'; end if;
  insert into public.audit_logs(actor_id, action)
  values (auth.uid(), 'attendance.window.closed');
end;
$$;

-- 8. Remove the old unrestricted per-day attendance endpoint.
-- This is essential: keeping it would bypass the new timetable gate.
drop function if exists public.mark_my_attendance();

-- 9. Student check-ins must match their section, today's scheduled class,
-- an open admin window, and the current time of day. All checked in SQL.
create or replace function public.mark_my_attendance(p_schedule_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_profile public.student_profiles%rowtype;
  v_schedule public.class_schedules%rowtype;
  v_window public.attendance_windows%rowtype;
  v_record public.attendance_records%rowtype;
  v_now timestamptz := now();
  v_manila timestamp := now() at time zone 'Asia/Manila';
begin
  if not public.is_approved_student() then
    raise exception 'Approved student account and valid session required'
      using errcode = '42501';
  end if;

  select * into v_profile from public.student_profiles where user_id = auth.uid();
  if not found then raise exception 'Student profile not found'; end if;

  select s.* into v_schedule from public.class_schedules s
  join public.sections sec on sec.id = s.section_id and sec.is_active
  join public.subjects sub on sub.id = s.subject_id and sub.is_active
  where s.id = p_schedule_id and s.section_id = v_profile.section_id;
  if not found then
    raise exception 'This class is not assigned to your approved section'
      using errcode = '42501';
  end if;
  if extract(isodow from v_manila)::smallint <> v_schedule.weekday
     or v_manila::time < v_schedule.start_time
     or v_manila::time >= v_schedule.end_time then
    raise exception 'Attendance is only available during your scheduled class in Philippine time';
  end if;

  -- Locks serialize check-ins with a concurrent admin close.
  select * into v_window from public.attendance_windows w
  where w.schedule_id = v_schedule.id
    and w.meeting_date = v_manila::date and w.is_open
    and w.opened_at <= v_now and w.expires_at > v_now
  for share;
  if not found then raise exception 'Your instructor has not opened attendance for this class'; end if;

  insert into public.attendance_records(
    student_id, subject_id, attendance_date, attendance_window_id
  ) values (
    auth.uid(), v_schedule.subject_id, v_manila::date, v_window.id
  ) on conflict do nothing
  returning * into v_record;

  if v_record.id is null then
    select * into v_record from public.attendance_records
    where student_id = auth.uid() and attendance_window_id = v_window.id;
  else
    insert into public.audit_logs(actor_id, action, subject_user_id)
    values (auth.uid(), 'attendance.marked', auth.uid());
  end if;

  return jsonb_build_object('id', v_record.id, 'schedule_id', v_schedule.id,
    'attendance_date', v_record.attendance_date, 'marked_at', v_record.marked_at,
    'status', v_record.status);
end;
$$;

-- Privilege discipline: the browser cannot call admin functions as anon,
-- and ordinary users cannot pass the is_admin() database check.
revoke all on function public.open_class_attendance(bigint),
  public.close_class_attendance(bigint), public.mark_my_attendance(bigint)
  from public, anon, authenticated;
grant execute on function public.open_class_attendance(bigint),
  public.close_class_attendance(bigint), public.mark_my_attendance(bigint)
  to authenticated;

commit;
