-- Student Monitoring System: initial schema and database-level authorization.
-- Apply with a privileged database role. No SERVICE_ROLE key is ever used in the browser.

create table public.sections (
  id bigint generated by default as identity primary key,
  code text not null unique check (char_length(trim(code)) between 2 and 40),
  is_active boolean not null default true
);

create table public.subjects (
  id bigint generated by default as identity primary key,
  code text not null unique check (char_length(trim(code)) between 2 and 40),
  name text not null check (char_length(trim(name)) between 2 and 120),
  is_active boolean not null default true
);

create table public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.portal_sessions (
  user_id uuid not null references auth.users(id) on delete cascade,
  auth_session_id uuid not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz,
  primary key (user_id, auth_session_id)
);

create table public.student_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  surname text not null check (char_length(trim(surname)) between 1 and 80),
  first_name text not null check (char_length(trim(first_name)) between 1 and 80),
  middle_initial text not null check (middle_initial ~ '^[A-Za-z]$' or middle_initial = 'N/A'),
  sex text not null check (sex in ('Male', 'Female', 'Prefer not to say')),
  age integer not null check (age between 12 and 99),
  section_id bigint not null references public.sections(id),
  subject_id bigint not null references public.subjects(id),
  github_username text not null unique check (github_username ~ '^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?$'),
  is_approved boolean not null default false,
  completed_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.attendance_records (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.student_profiles(user_id) on delete cascade,
  subject_id bigint not null references public.subjects(id),
  attendance_date date not null,
  marked_at timestamptz not null default now(),
  status text not null default 'Present' check (status = 'Present'),
  unique (student_id, subject_id, attendance_date)
);

create index attendance_date_idx on public.attendance_records(attendance_date desc);
create index attendance_student_idx on public.attendance_records(student_id, attendance_date desc);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  subject_user_id uuid,
  created_at timestamptz not null default now()
);

alter table public.sections enable row level security;
alter table public.subjects enable row level security;
alter table public.admin_users enable row level security;
alter table public.portal_sessions enable row level security;
alter table public.student_profiles enable row level security;
alter table public.attendance_records enable row level security;
alter table public.audit_logs enable row level security;

-- All browser writes occur through vetted SECURITY DEFINER functions.
revoke all on public.sections, public.subjects, public.admin_users, public.portal_sessions,
  public.student_profiles, public.attendance_records, public.audit_logs
  from public, anon, authenticated;
grant select on public.sections, public.subjects, public.student_profiles,
  public.attendance_records, public.audit_logs to authenticated;

-- Verify JWT user, portal-session record and the actual Supabase Auth session.
-- Checking auth.sessions makes even a previously issued JWT lose protected DB access
-- after an external/global Supabase sign-out removes that Auth session.
create function public.portal_session_active() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.portal_sessions p
    join auth.sessions s on s.id = p.auth_session_id and s.user_id = p.user_id
    where p.user_id = auth.uid()
      and p.auth_session_id = nullif(auth.jwt()->>'session_id', '')::uuid
      and p.revoked_at is null
      and p.created_at > now() - interval '8 hours'
      and p.last_seen_at > now() - interval '30 minutes'
  );
$$;

-- Only identity_data from Supabase's protected auth.identities is trusted.
-- raw_user_meta_data is intentionally NOT used: users can edit user metadata.
create function public.current_github_username() returns text
language sql stable security definer set search_path = '' as $$
  select lower(coalesce(
      nullif(i.identity_data->>'user_name', ''),
      nullif(i.identity_data->>'preferred_username', ''),
      nullif(i.identity_data->>'login', '')
    ))
  from auth.identities i
  where i.user_id = auth.uid() and i.provider = 'github'
  limit 1;
$$;

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select public.portal_session_active() and exists (
    select 1 from public.admin_users a where a.user_id = auth.uid()
  );
$$;

create function public.is_approved_student() returns boolean
language sql stable security definer set search_path = '' as $$
  select public.portal_session_active()
    and public.current_github_username() is not null
    and exists (
      select 1 from public.student_profiles p
      where p.user_id = auth.uid()
        and p.is_approved
        and lower(p.github_username) = public.current_github_username()
    );
$$;

-- Called after each GitHub sign-in, on page transitions, and during actual activity.
-- An expired/revoked session CANNOT be restarted. Another GitHub sign-in
-- creates a different auth.sessions.id and therefore a different portal session.
create function public.touch_portal_session() returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_sid uuid := nullif(auth.jwt()->>'session_id', '')::uuid;
begin
  if v_uid is null or v_sid is null or not exists (
    select 1 from auth.sessions where id = v_sid and user_id = v_uid
  ) then
    raise exception 'Authentication session is invalid' using errcode = '28000';
  end if;

  -- Anchor the absolute lifetime to the ORIGINAL Supabase Auth session creation.
  insert into public.portal_sessions(user_id, auth_session_id, created_at, last_seen_at)
  select v_uid, v_sid, s.created_at, s.created_at
  from auth.sessions s where s.id = v_sid and s.user_id = v_uid
  on conflict do nothing;

  update public.portal_sessions
  set last_seen_at = now()
  where user_id = v_uid and auth_session_id = v_sid
    and revoked_at is null
    and created_at > now() - interval '8 hours'
    and last_seen_at > now() - interval '30 minutes';

  if not found then
    raise exception 'Portal session has expired; sign in again' using errcode = '28000';
  end if;
  return true;
end;
$$;

create function public.end_portal_session() returns void
language plpgsql security definer set search_path = '' as $$
begin
  update public.portal_sessions
  set revoked_at = coalesce(revoked_at, now())
  where user_id = auth.uid()
    and auth_session_id = nullif(auth.jwt()->>'session_id','')::uuid;
end;
$$;

create function public.save_student_profile(
  p_surname text, p_first_name text, p_middle_initial text,
  p_sex text, p_age integer, p_section_id bigint,
  p_subject_id bigint, p_github_username text
) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_github text := public.current_github_username();
  v_handle text := lower(trim(coalesce(p_github_username, '')));
  v_profile public.student_profiles%rowtype;
begin
  if not public.portal_session_active() or v_uid is null then
    raise exception 'Session expired; sign in again';
  end if;
  if v_github is null or v_handle <> v_github then
    raise exception 'GitHub username must match your authenticated GitHub account';
  end if;
  if v_handle !~ '^[a-z0-9](?:[a-z0-9-]{0,37}[a-z0-9])?$' then
    raise exception 'Invalid GitHub username';
  end if;
  if trim(coalesce(p_surname, '')) = '' or char_length(trim(p_surname)) > 80
     or trim(coalesce(p_first_name, '')) = '' or char_length(trim(p_first_name)) > 80
     or coalesce(trim(p_middle_initial),'') !~ '^[A-Za-z]$' and coalesce(trim(p_middle_initial),'') <> 'N/A'
     or p_sex is null or p_sex not in ('Male','Female','Prefer not to say')
     or p_age is null or p_age not between 12 and 99 then
    raise exception 'Student information is incomplete or invalid';
  end if;
  if not exists (select 1 from public.sections where id = p_section_id and is_active)
     or not exists (select 1 from public.subjects where id = p_subject_id and is_active) then
    raise exception 'Select a valid active section and subject';
  end if;

  select * into v_profile from public.student_profiles where user_id = v_uid for update;
  if found and v_profile.is_approved and
     (v_profile.section_id is distinct from p_section_id or
      v_profile.subject_id is distinct from p_subject_id) then
    raise exception 'Ask the administrator before changing an approved section or subject';
  end if;

  insert into public.student_profiles(
    user_id, surname, first_name, middle_initial, sex, age,
    section_id, subject_id, github_username
  ) values (
    v_uid, trim(p_surname), trim(p_first_name), trim(p_middle_initial), p_sex,
    p_age, p_section_id, p_subject_id, v_handle
  )
  on conflict (user_id) do update set
    surname = excluded.surname, first_name = excluded.first_name,
    middle_initial = excluded.middle_initial, sex = excluded.sex,
    age = excluded.age, section_id = excluded.section_id,
    subject_id = excluded.subject_id, github_username = excluded.github_username,
    updated_at = now();

  insert into public.audit_logs(actor_id, action, subject_user_id)
  values (v_uid, 'profile.saved', v_uid);
end;
$$;

-- For now attendance is a single daily self check-in for the student's subject.
-- Subject, date, identity and timestamp are derived by PostgreSQL, not the browser.
create function public.mark_my_attendance() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_profile public.student_profiles%rowtype;
  v_record public.attendance_records%rowtype;
  v_today date := (now() at time zone 'Asia/Manila')::date;
begin
  if not public.is_approved_student() then
    raise exception 'You must have an approved, complete profile and valid session';
  end if;
  select * into v_profile from public.student_profiles where user_id = auth.uid();
  insert into public.attendance_records(student_id, subject_id, attendance_date)
  values (auth.uid(), v_profile.subject_id, v_today)
  on conflict (student_id, subject_id, attendance_date) do nothing
  returning * into v_record;
  if v_record.id is null then
    select * into v_record from public.attendance_records
    where student_id = auth.uid() and subject_id = v_profile.subject_id
      and attendance_date = v_today;
  else
    insert into public.audit_logs(actor_id, action, subject_user_id)
    values (auth.uid(), 'attendance.marked', auth.uid());
  end if;
  return jsonb_build_object('date', v_record.attendance_date,
                            'marked_at', v_record.marked_at, 'status', v_record.status);
end;
$$;

create function public.set_student_approval(p_student_id uuid, p_approved boolean)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if p_student_id is null or p_approved is null then
    raise exception 'Invalid approval request';
  end if;
  update public.student_profiles set is_approved = p_approved, updated_at = now()
  where user_id = p_student_id;
  if not found then
    raise exception 'Student was not found';
  end if;
  insert into public.audit_logs(actor_id, action, subject_user_id)
  values (auth.uid(), case when p_approved then 'student.approved' else 'student.revoked' end, p_student_id);
end;
$$;

-- Explicit EXECUTE privileges: no anonymous RPC endpoints.
revoke all on function public.portal_session_active(), public.current_github_username(),
  public.is_admin(), public.is_approved_student(), public.touch_portal_session(),
  public.end_portal_session(), public.save_student_profile(text,text,text,text,integer,bigint,bigint,text),
  public.mark_my_attendance(), public.set_student_approval(uuid,boolean)
  from public, anon, authenticated;
grant execute on function public.portal_session_active(), public.current_github_username(),
  public.is_admin(), public.is_approved_student(), public.touch_portal_session(),
  public.end_portal_session(), public.save_student_profile(text,text,text,text,integer,bigint,bigint,text),
  public.mark_my_attendance(), public.set_student_approval(uuid,boolean)
  to authenticated;

create policy sections_read on public.sections for select to authenticated
using ((select public.portal_session_active()));
create policy subjects_read on public.subjects for select to authenticated
using ((select public.portal_session_active()));
create policy profiles_read on public.student_profiles for select to authenticated
using ((user_id = (select auth.uid()) and (select public.portal_session_active()))
       or (select public.is_admin()));
create policy attendance_read on public.attendance_records for select to authenticated
using ((student_id = (select auth.uid()) and (select public.is_approved_student()))
       or (select public.is_admin()));
create policy audit_admin_read on public.audit_logs for select to authenticated
using ((select public.is_admin()));

